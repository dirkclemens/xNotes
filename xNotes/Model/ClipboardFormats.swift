import AppKit
import UniformTypeIdentifiers

/// Pasteboard type knowledge: the marker types from the nspasteboard.org convention
/// and readable names for the formats shown in the clipboard tooltips.
enum ClipboardFormats {
    /// Passwords and other secrets (password managers set these).
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword", // older 1Password versions
    ]

    /// Apps whose copies are always treated as sensitive because they don't mark
    /// passwords themselves (Apple's Passwords app, Keychain Access).
    static let passwordSourceApps: Set<String> = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
    ]

    /// Short-lived content the source app restores right away (e.g. snippet tools
    /// that paste through the clipboard). Never recorded.
    static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
    ]

    /// Content an app put on the clipboard without a user action. Never recorded.
    static let autoGeneratedTypes: Set<String> = [
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// The text as a web link if it is exactly one http(s) URL (no spaces, has a host).
    static func webURL(in text: String) -> URL? {
        let candidate = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !candidate.isEmpty,
              !candidate.contains(where: { $0.isWhitespace || $0.isNewline }),
              let url = URL(string: candidate),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
              let host = url.host, !host.isEmpty else { return nil }
        return url
    }

    /// Web link and its title as the source app put them on the pasteboard
    /// (`public.url` + `public.url-name`, or Safari/WebKit's URLs-with-titles list).
    static func copiedLink(on pasteboard: NSPasteboard) -> (url: String, title: String?)? {
        let urlsWithTitles = pasteboard.propertyList(forType: webURLsWithTitlesType) as? [[String]]
        let urlString = pasteboard.string(forType: .URL) ?? urlsWithTitles?.first?.first
        guard let urlString, webURL(in: urlString) != nil else { return nil }
        let title = pasteboard.string(forType: urlNameType)
            ?? urlsWithTitles.flatMap { $0.count > 1 ? $0[1].first : nil }
        return (urlString, title)
    }

    static let urlNameType = NSPasteboard.PasteboardType("public.url-name")
    private static let webURLsWithTitlesType = NSPasteboard.PasteboardType("WebURLsWithTitlesPboardType")

    /// Readable, de-duplicated names for the given pasteboard types, in order.
    /// Marker types and legacy aliases are left out.
    static func displayNames(for types: [String]) -> [String] {
        var names: [String] = []
        for type in types {
            guard let name = displayName(for: type), !names.contains(name) else { continue }
            names.append(name)
        }
        return names
    }

    private static func displayName(for type: String) -> String? {
        if concealedTypes.contains(type) || transientTypes.contains(type) || autoGeneratedTypes.contains(type) {
            return nil
        }
        if type == "org.nspasteboard.source" || type.hasPrefix("dyn.") {
            return nil
        }
        // Legacy Carbon/NeXT aliases ("NeXT Rich Text Format v1.0 pasteboard type", …)
        // duplicate the UTI-based entries.
        if type.contains(" ") {
            return nil
        }
        if let name = knownNames[type] {
            return name
        }
        if let description = UTType(type)?.localizedDescription, !description.isEmpty {
            return description
        }
        return type
    }

    private static let knownNames: [String: String] = [
        "public.utf8-plain-text": "Plain Text",
        "public.utf16-plain-text": "Plain Text",
        "public.utf16-external-plain-text": "Plain Text",
        "public.plain-text": "Plain Text",
        "public.rtf": "Rich Text (RTF)",
        "com.apple.flat-rtfd": "Rich Text with Attachments (RTFD)",
        "public.html": "HTML",
        "com.apple.webarchive": "Web Archive",
        "public.png": "PNG Image",
        "public.tiff": "TIFF Image",
        "public.jpeg": "JPEG Image",
        "com.compuserve.gif": "GIF Image",
        "public.heic": "HEIC Image",
        "com.adobe.pdf": "PDF",
        "public.file-url": "File",
        "public.url": "Link",
        "public.url-name": "Link Title",
        "com.apple.cocoa.pasteboard.color": "Color",
        "com.apple.cocoa.pasteboard.character-formatting": "Character Formatting",
        "com.apple.cocoa.pasteboard.paragraph-formatting": "Paragraph Formatting",
    ]
}
